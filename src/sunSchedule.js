// Sunrise and sunset, and a Witty Pi 4 schedule script (schedule.wpi) built from them that powers the Pi from just before
// sunrise to just after sunset, every day. The Witty Pi's schedule is a loop of ON and OFF states with fixed durations, so
// it cannot follow the sun by itself; instead the script has one ON/OFF pair per day, each worked out from that day's
// sunrise and sunset at a place. wittySchedule.js (the boat dashboard's Witty Pi card) uses buildSchedule.
//
// Sunrise and sunset use the standard NOAA/Wikipedia "sunrise equation" (solar transit +- hour angle, 0.833 degrees for the
// refraction and the sun's radius); it is good to about a minute away from the poles, which is far finer than needed here.
// Times in the script are the Pi's local time (its timezone must be right). beforeMin / afterMin are minutes of margin
// around sunrise / sunset (a boat needs time to boot and find a GPS fix). By default every ON state ends with WAIT: the Witty
// Pi schedules no shutdown and the boat shuts itself down when idle; hardStop leaves WAIT off so the Witty Pi shuts the Pi
// down at sunset + afterMin whatever it is doing. The script covers `days` days from `from` and then ends.

const RAD = Math.PI / 180;
const DAY_MS = 86400000;

// Sunrise and sunset (epoch ms) for the calendar day of `date` (local time) at the given place, or null for a day with no
// sunrise or sunset there (polar day or night).
function sunTimes(date, latDeg, lonDeg) {
  // The calendar date at the place (the Pi's own timezone is the place's). Day number n counts days from 2000-01-01 12:00 UTC to
  // that date's local solar noon, which is 12:00 UTC moved by the longitude (15 degrees = 1 hour, east is earlier).
  const solarNoonUtc = Date.UTC(date.getFullYear(), date.getMonth(), date.getDate(), 12, 0, 0) - (lonDeg / 15) * 3600000;
  const n = Math.round(solarNoonUtc / DAY_MS + 2440587.5 - 2451545.0);
  const jStar = n - lonDeg / 360; // mean solar time: the equation takes longitude east-positive
  const M = (357.5291 + 0.98560028 * jStar) % 360;
  const C = 1.9148 * Math.sin(M * RAD) + 0.02 * Math.sin(2 * M * RAD) + 0.0003 * Math.sin(3 * M * RAD);
  const lambda = (M + C + 180 + 102.9372) % 360;
  const jTransit = 2451545.0 + jStar + 0.0053 * Math.sin(M * RAD) - 0.0069 * Math.sin(2 * lambda * RAD);
  const delta = Math.asin(Math.sin(lambda * RAD) * Math.sin(23.4397 * RAD));
  const cosOmega =
    (Math.sin(-0.833 * RAD) - Math.sin(latDeg * RAD) * Math.sin(delta)) / (Math.cos(latDeg * RAD) * Math.cos(delta));
  if (cosOmega > 1 || cosOmega < -1) return null;
  const omega = Math.acos(cosOmega) / RAD; // hour angle, degrees
  const toMs = (j) => Math.round((j - 2440587.5) * DAY_MS);
  return { sunrise: toMs(jTransit - omega / 360), sunset: toMs(jTransit + omega / 360) };
}

// "H11 M5 S30" for a duration; at least one second, so a state is never empty.
function formatDuration(ms) {
  let s = Math.max(1, Math.round(ms / 1000));
  const h = Math.floor(s / 3600);
  s -= h * 3600;
  const m = Math.floor(s / 60);
  s -= m * 60;
  return [h && `H${h}`, m && `M${m}`, s && `S${s}`].filter(Boolean).join(' ') || 'S1';
}

const pad = (v) => String(v).padStart(2, '0');
// The Witty Pi's date format, in the Pi's local time
function formatLocal(ms) {
  const d = new Date(ms);
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}`;
}

// The schedule text. `from` is a Date (the first day), `days` the number of days covered.
function buildSchedule({ lat, lon, from, days, beforeMin = 30, afterMin = 30, hardStop = false }) {
  const days1 = [];
  for (let i = 0; i <= days; i++) {
    // one more day than asked: the last OFF state runs to the next sunrise
    const day = new Date(from.getFullYear(), from.getMonth(), from.getDate() + i, 12, 0, 0);
    const t = sunTimes(day, lat, lon);
    if (!t) throw new Error(`no sunrise or sunset on ${formatLocal(day.getTime()).slice(0, 10)} at ${lat}, ${lon} (polar day or night)`);
    days1.push({ on: t.sunrise - beforeMin * 60000, off: t.sunset + afterMin * 60000 });
  }
  const lines = [
    `# Witty Pi 4 schedule: on ${beforeMin} min before sunrise, ${hardStop ? 'off' : 'self-shutdown after'} ${afterMin} min after sunset, every day.`,
    `# Generated by the boat's Witty Pi card (sunSchedule.js) for ${lat}, ${lon}, ${days} days from ${formatLocal(days1[0].on).slice(0, 10)}. Regenerate before it ends.`,
    `# ${hardStop ? 'Each ON state ends with a shutdown' : 'ON ... WAIT: no shutdown is scheduled, the boat halts itself when idle'}.`,
    `BEGIN ${formatLocal(days1[0].on)}`,
    `END   ${formatLocal(days1[days].on)}`,
  ];
  for (let i = 0; i < days; i++) {
    const onMs = days1[i].off - days1[i].on;
    const offMs = days1[i + 1].on - days1[i].off;
    lines.push(`ON    ${formatDuration(onMs)}${hardStop ? '' : ' WAIT'}`);
    lines.push(`OFF   ${formatDuration(offMs)}`);
  }
  return lines.join('\n') + '\n';
}

module.exports = { sunTimes, formatDuration, formatLocal, buildSchedule };
